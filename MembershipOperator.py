numbers = [10, 20, 30, 40]

print(20 in numbers)     # True
print(50 not in numbers) # True
print(10 not in numbers) # False
 
word = "Python"

print('P' in word)       # True (because 'P' is in "Python")
print('p' in word)       # False (Python is case-sensitive)
print('z' not in word)   # True (because 'z' is not in "Python")


fruits = ('apple', 'banana', 'cherry')

print('apple' in fruits)       # True
print('mango' not in fruits)   # True

