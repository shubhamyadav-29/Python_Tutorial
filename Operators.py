# Arithmetic Operators
a = 10
b = 3
print(a + b)   # 13
print(a - b)   # 7
print(a * b)   # 30
print(a / b)   # 3.333...
print(a // b)  # 3 (floor division)
print(a % b)   # 1 (remainder)
print(a ** b)  # 1000 (10^3)

# Comparison Operators
print(a > b)   # True
print(a == 10) # True
print(a != 5)  # True

# Logical Operators
print((a > 5) and (b < 5))  # True
print((a < 5) or (b < 5))   # True
print(not(a > b))           # False

# Assignment Operators
x = 5
x += 3   # x = x + 3
print(x) # 8
